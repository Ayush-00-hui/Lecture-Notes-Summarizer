import io
import json
from typing import Union
from xml.sax.saxutils import escape as xml_escape
from docx import Document as DocxDoc
from docx.shared import RGBColor
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

from backend.app.db.schemas import StudyPackageOutput, CompareResponse

class ExporterService:
    @staticmethod
    def to_markdown(data: Union[StudyPackageOutput, CompareResponse], title: str = "NoteNest Study Export") -> str:
        """Exports either single study package or comparison report to clean Markdown."""
        lines = [f"# {title}\n", "*Generated by NoteNest — AI Lecture Notes Summarizer*\n", "---\n"]

        if isinstance(data, StudyPackageOutput):
            lines.append("## Executive Summary\n")
            lines.append(f"{data.summary}\n\n")

            if data.key_concepts:
                lines.append("## Key Concepts\n")
                for c in data.key_concepts:
                    lines.append(f"- **{c.term}** ({c.importance} Importance | Reference: {c.source_reference})")
                    lines.append(f"  {c.definition}\n")

            if data.revision_points:
                lines.append("\n## Revision & Exam Preparation\n")
                for r in data.revision_points:
                    lines.append(f"- [{r.topic}] {r.point}")
                    if r.exam_question_hint:
                        lines.append(f"  *Likely Exam Question:* {r.exam_question_hint}")

            if data.flashcards:
                lines.append("\n## Spaced Repetition Flashcards\n")
                for idx, f in enumerate(data.flashcards):
                    lines.append(f"**Card {idx+1} ({f.category})**")
                    lines.append(f"- **Q:** {f.question}")
                    lines.append(f"- **A:** {f.answer}\n")

        elif isinstance(data, CompareResponse):
            lines.append("## Prompt Comparison Lab: Benchmark Report\n")
            lines.append(f"**Verdict:** {data.verdict_summary}\n\n")

            lines.append("### Objective Metrics Comparison\n")
            lines.append("| Metric | Prompt A (Direct) | Prompt B (Structured) |")
            lines.append("|---|---|---|")
            lines.append(f"| Word Count | {data.metrics_a.word_count} | {data.metrics_b.word_count} |")
            lines.append(f"| Compression Ratio | {data.metrics_a.compression_ratio} | {data.metrics_b.compression_ratio} |")
            lines.append(f"| Latency | {data.metrics_a.latency_ms} ms | {data.metrics_b.latency_ms} ms |")
            lines.append(f"| Concept Coverage | {data.metrics_a.concept_coverage_pct}% | {data.metrics_b.concept_coverage_pct}% |")
            lines.append(f"| Readability (Flesch-Kincaid) | Grade {data.metrics_a.flesch_kincaid_grade} | Grade {data.metrics_b.flesch_kincaid_grade} |")
            lines.append(f"| Redundancy Score | {data.metrics_a.redundancy_score}% | {data.metrics_b.redundancy_score}% |")
            lines.append(f"| Hallucination Risk | {data.metrics_a.hallucination_risk_pct}% | {data.metrics_b.hallucination_risk_pct}% |\n\n")

            if data.llm_judge:
                lines.append("### LLM Judge Evaluation\n")
                lines.append(f"*Assessment:* {data.llm_judge.comparison_summary}\n\n")
                lines.append(f"- **Prompt A:** Faithfulness: {data.llm_judge.score_a.faithfulness}/5 | Coverage: {data.llm_judge.score_a.coverage}/5 | Clarity: {data.llm_judge.score_a.clarity}/5 | Conciseness: {data.llm_judge.score_a.conciseness}/5")
                lines.append(f"  *Rationale:* {data.llm_judge.score_a.rationale}\n")
                lines.append(f"- **Prompt B:** Faithfulness: {data.llm_judge.score_b.faithfulness}/5 | Coverage: {data.llm_judge.score_b.coverage}/5 | Clarity: {data.llm_judge.score_b.clarity}/5 | Conciseness: {data.llm_judge.score_b.conciseness}/5")
                lines.append(f"  *Rationale:* {data.llm_judge.score_b.rationale}\n\n")

            lines.append("### Output A: Direct Zero-Shot Summary\n")
            lines.append(f"{data.output_a.summary}\n\n")

            lines.append("### Output B: Structured Scaffold Summary\n")
            lines.append(f"{data.output_b.summary}\n\n")

        return "\n".join(lines)

    @staticmethod
    def to_docx(data: Union[StudyPackageOutput, CompareResponse], title: str = "NoteNest Study Export") -> bytes:
        """Exports to a styled Microsoft Word document (.docx)."""
        doc = DocxDoc()
        
        # Title
        h1 = doc.add_heading(title, level=0)
        h1.runs[0].font.color.rgb = RGBColor(79, 70, 229)  # Indigo
        doc.add_paragraph("Generated by NoteNest — AI Lecture Notes Summarizer").italic = True

        if isinstance(data, StudyPackageOutput):
            doc.add_heading("Executive Summary", level=1)
            doc.add_paragraph(data.summary)

            if data.key_concepts:
                doc.add_heading("Key Concepts", level=1)
                for c in data.key_concepts:
                    p = doc.add_paragraph()
                    r1 = p.add_run(f"{c.term} ")
                    r1.bold = True
                    r2 = p.add_run(f"[{c.importance} | {c.source_reference}]\n")
                    r2.italic = True
                    p.add_run(c.definition)

            if data.revision_points:
                doc.add_heading("Revision Points & Exam Hints", level=1)
                for r in data.revision_points:
                    p = doc.add_paragraph(style='List Bullet')
                    r1 = p.add_run(f"({r.topic}) ")
                    r1.bold = True
                    p.add_run(r.point)
                    if r.exam_question_hint:
                        hint_p = doc.add_paragraph(style='List Bullet 2')
                        hint_p.add_run(f"Exam Hint: {r.exam_question_hint}").italic = True

            if data.flashcards:
                doc.add_heading("Spaced Repetition Flashcards", level=1)
                for idx, f in enumerate(data.flashcards):
                    p = doc.add_paragraph()
                    p.add_run(f"Q{idx+1} ({f.category}): ").bold = True
                    p.add_run(f.question + "\n")
                    p.add_run("Answer: ").bold = True
                    p.add_run(f.answer)

        elif isinstance(data, CompareResponse):
            doc.add_heading("Prompt Comparison Lab: Benchmark Report", level=1)
            doc.add_paragraph(f"Verdict: {data.verdict_summary}").bold = True

            doc.add_heading("Objective Metrics", level=2)
            table = doc.add_table(rows=1, cols=3)
            hdr_cells = table.rows[0].cells
            hdr_cells[0].text = "Metric"
            hdr_cells[1].text = "Prompt A (Direct)"
            hdr_cells[2].text = "Prompt B (Structured)"

            metrics_rows = [
                ("Word Count", str(data.metrics_a.word_count), str(data.metrics_b.word_count)),
                ("Compression Ratio", str(data.metrics_a.compression_ratio), str(data.metrics_b.compression_ratio)),
                ("Latency (ms)", str(data.metrics_a.latency_ms), str(data.metrics_b.latency_ms)),
                ("Concept Coverage", f"{data.metrics_a.concept_coverage_pct}%", f"{data.metrics_b.concept_coverage_pct}%"),
                ("Flesch-Kincaid Grade", str(data.metrics_a.flesch_kincaid_grade), str(data.metrics_b.flesch_kincaid_grade)),
                ("Redundancy Score", f"{data.metrics_a.redundancy_score}%", f"{data.metrics_b.redundancy_score}%"),
                ("Hallucination Risk", f"{data.metrics_a.hallucination_risk_pct}%", f"{data.metrics_b.hallucination_risk_pct}%"),
            ]
            for m_name, val_a, val_b in metrics_rows:
                row_cells = table.add_row().cells
                row_cells[0].text = m_name
                row_cells[1].text = val_a
                row_cells[2].text = val_b

            doc.add_heading("Output A Summary", level=2)
            doc.add_paragraph(data.output_a.summary)
            doc.add_heading("Output B Summary", level=2)
            doc.add_paragraph(data.output_b.summary)

        out_stream = io.BytesIO()
        doc.save(out_stream)
        return out_stream.getvalue()

    @staticmethod
    def to_pdf(data: Union[StudyPackageOutput, CompareResponse], title: str = "NoteNest Study Export") -> bytes:
        """Exports to a styled PDF using ReportLab."""
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=40, leftMargin=40, topMargin=40, bottomMargin=40)
        
        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            'TitleStyle',
            parent=styles['Heading1'],
            fontSize=22,
            leading=26,
            textColor=colors.HexColor('#4f46e5'),
            spaceAfter=8
        )
        h2_style = ParagraphStyle(
            'Heading2Style',
            parent=styles['Heading2'],
            fontSize=14,
            leading=18,
            textColor=colors.HexColor('#1e1b4b'),
            spaceBefore=12,
            spaceAfter=6
        )
        body_style = ParagraphStyle(
            'BodyStyle',
            parent=styles['Normal'],
            fontSize=10,
            leading=14,
            textColor=colors.HexColor('#1e293b'),
            spaceAfter=8
        )

        cell_style = ParagraphStyle(
            'CellStyle',
            parent=styles['Normal'],
            fontSize=8.5,
            leading=11.5,
            textColor=colors.HexColor('#1e293b'),
        )
        header_cell_style = ParagraphStyle(
            'HeaderCellStyle',
            parent=styles['Normal'],
            fontSize=8.5,
            leading=11.5,
            fontName='Helvetica-Bold',
            textColor=colors.HexColor('#18181b'),
        )

        elements = []
        elements.append(Paragraph(xml_escape(title), title_style))
        elements.append(Paragraph("<i>Generated by NoteNest — Lecture Notes Summarizer</i>", body_style))
        elements.append(Spacer(1, 12))

        if isinstance(data, StudyPackageOutput):
            elements.append(Paragraph("Summary", h2_style))
            # Clean markdown headings and escape XML for PDF paragraph
            clean_summary = xml_escape(data.summary.replace("#", "").replace("**", "")).replace("\n", "<br/>")
            elements.append(Paragraph(clean_summary, body_style))
            elements.append(Spacer(1, 10))

            if data.key_concepts:
                elements.append(Paragraph("Key Concepts", h2_style))
                table_data = [[
                    Paragraph("Term", header_cell_style),
                    Paragraph("Source", header_cell_style),
                    Paragraph("Definition", header_cell_style),
                ]]
                for c in data.key_concepts:
                    table_data.append([
                        Paragraph(f"<b>{xml_escape(c.term)}</b>", cell_style),
                        Paragraph(xml_escape(c.source_reference or ""), cell_style),
                        Paragraph(xml_escape(c.definition), cell_style),
                    ])
                
                t = Table(table_data, colWidths=[115, 75, 330], repeatRows=1)
                t.setStyle(TableStyle([
                    ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#f4f4f5')),
                    ('VALIGN', (0,0), (-1,-1), 'TOP'),
                    ('TOPPADDING', (0,0), (-1,-1), 5),
                    ('BOTTOMPADDING', (0,0), (-1,-1), 5),
                    ('LEFTPADDING', (0,0), (-1,-1), 6),
                    ('RIGHTPADDING', (0,0), (-1,-1), 6),
                    ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#d4d4d8')),
                ]))
                elements.append(t)
                elements.append(Spacer(1, 14))

            if data.revision_points:
                elements.append(Paragraph("Key Revision Points", h2_style))
                for r in data.revision_points:
                    elements.append(Paragraph(f"• <b>[{xml_escape(r.topic)}]</b> {xml_escape(r.point)}", body_style))

        elif isinstance(data, CompareResponse):
            elements.append(Paragraph("Prompt Comparison Lab: Benchmark Report", h2_style))
            elements.append(Paragraph(f"<b>Verdict:</b> {data.verdict_summary}", body_style))
            elements.append(Spacer(1, 10))

            table_data = [
                ["Metric", "Prompt A (Direct)", "Prompt B (Structured)"],
                ["Word Count", str(data.metrics_a.word_count), str(data.metrics_b.word_count)],
                ["Compression Ratio", str(data.metrics_a.compression_ratio), str(data.metrics_b.compression_ratio)],
                ["Latency", f"{data.metrics_a.latency_ms} ms", f"{data.metrics_b.latency_ms} ms"],
                ["Concept Coverage", f"{data.metrics_a.concept_coverage_pct}%", f"{data.metrics_b.concept_coverage_pct}%"],
                ["Flesch-Kincaid Grade", str(data.metrics_a.flesch_kincaid_grade), str(data.metrics_b.flesch_kincaid_grade)],
                ["Redundancy", f"{data.metrics_a.redundancy_score}%", f"{data.metrics_b.redundancy_score}%"],
                ["Hallucination Risk", f"{data.metrics_a.hallucination_risk_pct}%", f"{data.metrics_b.hallucination_risk_pct}%"]
            ]
            t = Table(table_data, colWidths=[180, 170, 170])
            t.setStyle(TableStyle([
                ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#e0e7ff')),
                ('TEXTCOLOR', (0,0), (-1,0), colors.HexColor('#312e81')),
                ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
                ('FONTSIZE', (0,0), (-1,-1), 9),
                ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#cbd5e1')),
            ]))
            elements.append(t)

        doc.build(elements)
        return buffer.getvalue()

    @staticmethod
    def to_txt(data: Union[StudyPackageOutput, CompareResponse], title: str = "NoteNest Summary") -> str:
        """Exports to clean plain text (.txt)."""
        lines = [title.upper(), "=" * len(title), "Generated by NoteNest — Lecture Notes Summarizer", ""]

        if isinstance(data, StudyPackageOutput):
            lines.append("SUMMARY")
            lines.append("-" * 40)
            clean_summary = data.summary.replace("### ", "").replace("## ", "").replace("# ", "").replace("**", "")
            lines.append(clean_summary)
            lines.append("")

            if data.key_concepts:
                lines.append("KEY CONCEPTS")
                lines.append("-" * 40)
                for c in data.key_concepts:
                    ref = f" ({c.source_reference})" if c.source_reference else ""
                    lines.append(f"* {c.term}{ref}: {c.definition}")
                lines.append("")

            if data.revision_points:
                lines.append("REVISION POINTS")
                lines.append("-" * 40)
                for r in data.revision_points:
                    lines.append(f"- [{r.topic}] {r.point}")
                lines.append("")

        elif isinstance(data, CompareResponse):
            lines.append("COMPARISON VERDICT")
            lines.append("-" * 40)
            lines.append(data.verdict_summary)
            lines.append("")
            lines.append("OUTPUT A")
            lines.append(data.output_a.summary)
            lines.append("")
            lines.append("OUTPUT B")
            lines.append(data.output_b.summary)

        return "\n".join(lines)

    @staticmethod
    def to_json(data: Union[StudyPackageOutput, CompareResponse]) -> str:
        """Exports data to formatted JSON string."""
        if hasattr(data, "model_dump"):
            return json.dumps(data.model_dump(), indent=2)
        return json.dumps(data, indent=2)
